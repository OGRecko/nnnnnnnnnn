/**
 * Directivity FIDELITY gate: does the solver's directional source actually radiate the pattern it was given?
 *
 * Method: a source in the middle of a large room (receivers well outside the solver's injection cluster) is given a pattern whose
 * front-to-rear difference is known from the data itself. The same room is run omnidirectionally as the symmetry baseline, then
 * with the pattern aimed forward and backward. The measured front/rear difference is compared with what the data specifies.
 *
 * Run: npm run validate:directivity. Exits 1 when the measured behaviour is outside tolerance. This is intentionally NOT part of
 * `npm test`: a failure here is a documented model limitation (see DIRECTIVITY-IMPORT.md), not a regression.
 */
import fs from 'node:fs';
import path from 'node:path';
import { runWave } from '../server/solverWorker';
import { getInterpolatedMagnitude } from '../server/directivityParser';

const rad = (d: number) => (d * Math.PI) / 180;
const FREQS = [250, 500];
const REAR_DB = -30;
const points: Record<string, number[]> = {};
for (let el = -90; el <= 90; el += 30) for (let az = 0; az < 360; az += 30) { const c = Math.cos(rad(az)) * Math.cos(rad(el)); const m = REAR_DB * (1 - c) / 2; points[`${az},${el}`] = FREQS.map(() => m); }
const data = { frequencies: FREQS, angularResolution: 30, points };
const expectedDb = getInterpolatedMagnitude({ ...data, brand: '', model: '' } as any, 500, 0, 0) - getInterpolatedMagnitude({ ...data, brand: '', model: '' } as any, 500, 180, 0);

const peak = (t: ArrayLike<number>) => { let m = 0; for (let i = 0; i < t.length; i++) m = Math.max(m, Math.abs(t[i])); return m; };
function frontRearDb(src: object): number {
  const log = console.log, warn = console.warn; console.log = () => {}; console.warn = () => {};
  try {
    const r: any = runWave({ L: 14, W: 14, H: 4, steps: 260, fmax: 500, accuracyMode: 'fast', poly: [{ x: 0, y: 0 }, { x: 1, y: 0 }, { x: 1, y: 1 }, { x: 0, y: 1 }], wallMaterial: 'drywall', floorMaterial: 'wood_floor', ceilMaterial: 'drywall',
      source: { x: .5, y: .5, z: 2, ...src }, receivers: [{ x: .5, y: .85, z: 2 }, { x: .5, y: .15, z: 2 }] });
    return 20 * Math.log10(peak(r.receiverTraces[0]) / peak(r.receiverTraces[1]));
  } finally { console.log = log; console.warn = warn; }
}

const TOLERANCE_DB = 3;
const omni = frontRearDb({});
const fwd = frontRearDb({ isDirectional: true, directivityData: data, yawDeg: 0 });
const back = frontRearDb({ isDirectional: true, directivityData: data, yawDeg: 180 });
const checks = [
  { name: 'omnidirectional baseline is symmetric', measured: omni, expected: 0, pass: Math.abs(omni) <= 0.5 },
  { name: 'aimed forward: front louder than rear by the specified amount', measured: fwd, expected: expectedDb, pass: Math.abs(fwd - expectedDb) <= TOLERANCE_DB },
  { name: 'aimed backward: rear louder than front by the specified amount', measured: back, expected: -expectedDb, pass: Math.abs(back + expectedDb) <= TOLERANCE_DB },
];
console.log(`\nDirectivity fidelity (pattern specifies ${expectedDb.toFixed(1)} dB front-to-rear; tolerance +/-${TOLERANCE_DB} dB)\n`);
for (const c of checks) console.log(`  ${c.pass ? 'PASS' : 'FAIL'}  ${c.name.padEnd(62)} measured ${c.measured.toFixed(2).padStart(6)} dB   expected ${c.expected.toFixed(1).padStart(6)} dB`);
const failed = checks.filter((c) => !c.pass).length;
// Recorded so the generated docs and the doc-consistency check use the latest MEASUREMENT instead of hand-typed numbers.
fs.writeFileSync(path.join(process.cwd(), 'directivity-fidelity-results.json'), JSON.stringify({
  note: 'GENERATED by scripts/validate-directivity-fidelity.ts (npm run validate:directivity). Do not edit by hand.',
  specifiedFrontRearDb: Number(expectedDb.toFixed(2)), toleranceDb: TOLERANCE_DB,
  omniDb: Number(omni.toFixed(2)), forwardDb: Number(fwd.toFixed(2)), backwardDb: Number(back.toFixed(2)), pass: failed === 0,
}, null, 1) + '\n');
console.log(failed ? `\nFAIL: ${failed}/${checks.length} checks. The solver's directional source does not reproduce the supplied pattern.` : '\nPASS: the solver reproduces the supplied pattern within tolerance.');
process.exit(failed ? 1 : 0);
