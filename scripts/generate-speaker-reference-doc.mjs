// Generates SAVED-PROJECT-SPEAKER-REFERENCES.md from src/data/archivedSpeakers.json (itself generated from the owner's archive
// files). Facts that change (file names, counts, redirects) are never typed by hand. `--check` fails if the file is stale.
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const idx = JSON.parse(fs.readFileSync(path.join(root, 'src/data/archivedSpeakers.json'), 'utf8'));
const live = JSON.parse(fs.readFileSync(path.join(root, 'src/data/speakers.json'), 'utf8')).length;
const files = Object.entries(idx.sources).map(([f, m]) => `- \`${f}\` (${m.count} record${m.count === 1 ? '' : 's'}, reviewed ${m.reviewDate})`).join('\n');
const redirects = Object.entries(idx.entries).filter(([, e]) => e.redirectTo).map(([id, e]) => `- \`${id}\` -> suggests \`${e.redirectTo}\``).join('\n') || '- none';

const doc = `# Saved projects that reference a speaker

GENERATED by \`scripts/generate-speaker-reference-doc.mjs\` from \`src/data/archivedSpeakers.json\`. Do not edit by hand; run \`npm run docs:release\`.

This describes what happens when a saved project names a speaker ID that is not in the live catalog (${live} live speakers; ${idx.count} archived IDs).

## What is recorded
- Each source in a project can carry an optional \`speakerId\`, plus the speaker-derived fields (brand, model, type, sensitivity, sensitivity reference, impedance) and the per-source \`soundType\`. All of these are saved and restored on open.
- A project can only be opened when every non-empty \`speakerId\` is in the live catalog (\`src/data/speakers.json\`).
- Archived records are not live and never become live again because a project mentions them.

## What happens on open
1. The file is read and fully validated. Nothing is applied to the open project yet.
2. If the **only** problem is missing speakers, the app shows the **replacement picker** instead of an error. Any other problem (a bad room size, a malformed file) still produces the normal "Failed to load project" message.
3. The picker lists each affected source and says whether its speaker was **archived** (with the archive reason and date) or is **not in the catalog** (a typo, an edited or damaged file).
4. For each source the person searches the live catalog and chooses a replacement. The project opens only when every affected source has a choice. Cancelling opens nothing.
5. The same picker is used when opening a project from local storage or recovering the autosave.

## Rules the picker follows
- **Never automatic.** A replacement is always an explicit per-source choice. An archive note that points to another speaker is shown as a *suggestion* with its own button; it is never applied on its own. Current suggestions:
${redirects}
- **Only missing speakers can be replaced.** A source whose speaker is live cannot be re-pointed through this path, and a choice for a source that does not need one is refused.
- **Replacements must be live.** An archived or unknown ID is never accepted as a replacement.
- **Your settings are kept.** Position, gain, delay, mute, orientation and sound selection stay. The speaker-derived fields come from the replacement, so the old speaker's sensitivity does not linger.
- **Polar data is dropped.** Custom directivity data was supplied for the original speaker and is removed (and reported) instead of silently applying to a different one.
- **The file is not modified.** Replacements apply to the in-memory project. Saving writes them.
- **History is recorded.** Each replacement is saved in the project as \`speakerReplacements\` (original ID and status, replacement ID, brand and model), up to 200 records, so the project's history stays visible and survives re-saves.

## How archived is told apart from unknown
The browser uses \`src/data/archivedSpeakers.json\`, generated by \`npm run data:archived-index\` from the owner's archive files in \`scripts/research/\`:
${files}

An ID found in none of these was never in the catalog. \`npm run data:archived-index:check\` fails if the index is stale or if an ID is both archived and live.

## What is not done
- No automatic remapping, ever.
- Archived records are not restored to make old projects open. The owner's archive decisions are preserved.
- Undo/redo does not revert the replacement history (it is a record of what you chose, not editable state).
`;

const out = path.join(root, 'SAVED-PROJECT-SPEAKER-REFERENCES.md');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== doc) { console.error('SAVED-PROJECT-SPEAKER-REFERENCES.md is stale; run: npm run docs:release'); process.exit(1); }
  console.log(JSON.stringify({ ok: true }));
} else { fs.writeFileSync(out, doc); console.log(JSON.stringify({ written: 'SAVED-PROJECT-SPEAKER-REFERENCES.md' })); }
