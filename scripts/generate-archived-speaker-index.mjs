// Builds src/data/archivedSpeakers.json from the owner's archive files in scripts/research/removed-*.json.
// The browser needs this to tell an ARCHIVED speaker ID from one that never existed when a saved project references it.
// Nothing here is hand-maintained. `--check` verifies the committed file is current and disjoint from the live catalog.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const researchDir = path.join(root, 'scripts', 'research');
const outPath = path.join(root, 'src', 'data', 'archivedSpeakers.json');
const live = new Set(JSON.parse(fs.readFileSync(path.join(root, 'src', 'data', 'speakers.json'), 'utf8')).map((s) => s.id));

const files = fs.readdirSync(researchDir).filter((f) => /^removed-.*\.json$/.test(f)).sort();
const entries = {};
const sources = {};
const problems = [];

for (const f of files) {
  const doc = JSON.parse(fs.readFileSync(path.join(researchDir, f), 'utf8'));
  const records = Array.isArray(doc.records) ? doc.records : Array.isArray(doc.entries) ? doc.entries : [];
  const meta = new Map((Array.isArray(doc.archiveMeta) ? doc.archiveMeta : []).map((m) => [m.id, m]));
  sources[f] = { reviewDate: doc.reviewDate ?? null, count: records.length };
  for (const r of records) {
    if (typeof r?.id !== 'string' || !r.id) { problems.push(`${f}: record without an id`); continue; }
    const m = meta.get(r.id);
    const entry = {
      brand: String(r.brand ?? ''), model: String(r.model ?? ''),
      reason: String(m?.reason ?? r.reason ?? doc.reason ?? '').slice(0, 400),
      archivedDate: m?.archivedDate ?? r.reviewDate ?? doc.reviewDate ?? null,
      source: f,
    };
    if (typeof m?.redirectTo === 'string' && m.redirectTo) entry.redirectTo = m.redirectTo;
    // The same ID can appear in several ledgers; keep the most recently dated entry.
    const prev = entries[r.id];
    if (!prev || String(entry.archivedDate ?? '') >= String(prev.archivedDate ?? '')) entries[r.id] = entry;
  }
}

for (const id of Object.keys(entries)) {
  if (live.has(id)) problems.push(`${id} is both archived and live`);
  const to = entries[id].redirectTo;
  if (to && !live.has(to)) { problems.push(`${id} redirects to ${to}, which is not live; dropping the suggestion`); delete entries[id].redirectTo; }
}

const sortedEntries = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
const out = {
  _comment: 'GENERATED by scripts/generate-archived-speaker-index.mjs from scripts/research/removed-*.json. Do not edit by hand.',
  count: Object.keys(sortedEntries).length,
  sources,
  entries: sortedEntries,
};
const text = JSON.stringify(out, null, 1) + '\n';

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  const bad = problems.filter((p) => !p.includes('dropping the suggestion'));
  if (current !== text) bad.push('src/data/archivedSpeakers.json is stale; run: npm run data:archived-index');
  if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
  console.log(JSON.stringify({ ok: true, archived: out.count, files: files.length }));
} else {
  fs.writeFileSync(outPath, text);
  console.log(JSON.stringify({ written: path.relative(root, outPath), archived: out.count, files: files.length, notes: problems }));
}
